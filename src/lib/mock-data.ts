// CineVerse mock dataset
// Realistic TMDB-shaped data for offline demo. When TMDB_API_KEY is set,
// src/lib/tmdb.ts will call the real API instead and this becomes the fallback.

export type MediaType = "MOVIE" | "TV" | "PERSON";

export interface Genre {
  id: number;
  name: string;
}

export interface CastMember {
  id: number;
  name: string;
  character: string;
  profileUrl: string;
  order: number;
}

export interface CrewMember {
  id: number;
  name: string;
  job: string;
  department: string;
  profileUrl: string;
}

export interface MediaItem {
  id: number;
  mediaType: MediaType;
  title: string;
  originalTitle: string;
  overview: string;
  tagline?: string;
  posterUrl: string;
  backdropUrl: string;
  releaseDate: string; // ISO date or year
  year: string;
  runtime?: number; // minutes
  seasons?: number;
  episodes?: number;
  voteAverage: number;
  voteCount: number;
  popularity: number;
  genres: number[];
  genreNames: string[];
  originalLanguage: string;
  originCountry: string[];
  status: string;
  budget?: number;
  revenue?: number;
  homepage?: string;
  imdbId?: string;
  tmdbId: number;
  certification?: string;
  keywords: string[];
  cast: CastMember[];
  crew: CrewMember[];
  similar: number[]; // ids
  recommendations: number[]; // ids
  belongsToCollection?: string;
  productionCompanies: { id: number; name: string; logoUrl?: string }[];
  networks?: { id: number; name: string; logoUrl?: string }[];
  trailerYoutubeId?: string;
  images: string[]; // additional backdrops
}

export interface Person {
  id: number;
  name: string;
  biography: string;
  profileUrl: string;
  birthdate?: string;
  birthplace?: string;
  deathdate?: string;
  department: string;
  knownFor: string;
  gender: string;
  placeOfOrigin: string;
  movieCredits: { id: number; title: string; character?: string; job?: string; year: string; posterUrl: string }[];
  tvCredits: { id: number; title: string; character?: string; job?: string; year: string; posterUrl: string }[];
  externalLinks: { label: string; url: string }[];
}

